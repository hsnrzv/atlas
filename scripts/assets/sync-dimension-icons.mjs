#!/usr/bin/env node
// Copies the Tabler outline icons chosen for the seven Life Dimensions
// (design/tokens/design-tokens.json → lifeDimensions.icons) into design/svg/dimensions/,
// normalised to the Atlas icon convention (24px grid, currentColor, stroke 1.75).
// `--check` fails if the committed SVGs are out of sync.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, loadManifest } from '../design-tokens/lib.mjs';

const CHECK = process.argv.includes('--check');
const tablerRoot = join(ROOT, 'node_modules', '@tabler', 'icons');
const tablerVersion = JSON.parse(readFileSync(join(tablerRoot, 'package.json'), 'utf8')).version;
const { lifeDimensions } = loadManifest();
const STROKE = 1.75;

let stale = 0;
for (const key of lifeDimensions.order) {
  const icon = lifeDimensions.icons[key];
  const source = readFileSync(join(tablerRoot, 'icons', 'outline', `${icon}.svg`), 'utf8');
  const body = source
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s*<path stroke="none" d="M0 0h24v24H0z" fill="none" \/>/, '')
    .trim()
    .split('\n')
    .map((line) => `  ${line.trim()}`)
    .join('\n');
  const label = lifeDimensions.longLabels[key];
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24" fill="none" stroke="currentColor" stroke-width="${STROKE}" stroke-linecap="round" stroke-linejoin="round" role="img" aria-label="${label}">
  <!-- Life Dimension: ${label}. Tabler Icons "${icon}" v${tablerVersion}, MIT License, (c) Paweł Kuna. Generated by scripts/assets/sync-dimension-icons.mjs. -->
${body}
</svg>
`;
  const target = join(ROOT, 'design', 'svg', 'dimensions', `${key}.svg`);
  const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
  if (CHECK) {
    if (current !== svg) {
      stale++;
      console.error(`✗ design/svg/dimensions/${key}.svg is out of sync with Tabler "${icon}"`);
    } else console.log(`✓ design/svg/dimensions/${key}.svg`);
  } else {
    writeFileSync(target, svg);
    console.log(
      `${current === svg ? '=' : '✎'} design/svg/dimensions/${key}.svg  ← tabler:${icon}`,
    );
  }
}
if (stale) process.exit(1);
